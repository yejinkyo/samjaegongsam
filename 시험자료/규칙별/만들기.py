def write(root: Path) -> None:
    for name, spec in CASES.items():
        folder = root / name
        folder.mkdir(parents=True, exist_ok=True)
        for old in folder.glob("*.json"):
            old.unlink()
        names = []
        for d in spec["docs"]:
            (folder / f"{d['doc_id']}.json").write_text(json.dumps(d, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            names.append(f"{d['doc_id']}.json")
        case = {"case_id": f"rule-{name}", "case_type": spec["case_type"], "as_of": AS_OF, "documents": names,
                "user_notes": [], "expect": spec["expect"], "why": spec["why"]}
        (folder / "case.json").write_text(json.dumps(case, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


